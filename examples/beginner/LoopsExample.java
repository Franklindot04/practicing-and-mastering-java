public class LoopsExample {
    public static void main(String[] args) {
        for (int number = 1; number <= 5; number++) {
            System.out.println("For loop number: " + number);
        }

        int countdown = 3;
        while (countdown > 0) {
            System.out.println("Countdown: " + countdown);
            countdown--;
        }
    }
}

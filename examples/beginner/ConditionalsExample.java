public class ConditionalsExample {
    public static void main(String[] args) {
        int score = 82;

        if (score >= 90) {
            System.out.println("Excellent");
        } else if (score >= 70) {
            System.out.println("Good progress");
        } else {
            System.out.println("Review and try again");
        }
    }
}
